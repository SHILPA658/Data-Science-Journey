# Python Functions Practice

# Creating a function
def greet(name):
    print("Hello", name)

# Calling a function
greet("Shilpa")

# Function with return statement
def add(a, b):
    return a + b

result = add(10, 20)
print("Sum:", result)


# Function to calculate square
def square(number):
    return number ** 2
print("Square:", square(5))
